// Pause and Num Lock: Windows' low-level hook reports Pause as 0x45 and Num
// Lock as 0x45 *extended* (the reverse of the hardware scancodes), so the table
// follows the hook; `SendInput` gets virtual-key codes for them instead.
pub const USAGE_PAUSE: u16 = 0x48;
pub const USAGE_NUM_LOCK: u16 = 0x53;

pub fn usage_from_scancode(scancode: u16, extended: bool) -> Option<u16> {
    TABLE
        .iter()
        .find(|&&(_, sc, ext)| sc == scancode && ext == extended)
        .map(|&(usage, _, _)| usage)
}

pub fn scancode_from_usage(usage: u16) -> Option<(u16, bool)> {
    TABLE.iter().find(|&&(u, _, _)| u == usage).map(|&(_, sc, ext)| (sc, ext))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn round_trips_and_has_no_duplicates() {
        for &(usage, sc, ext) in TABLE {
            assert_eq!(usage_from_scancode(sc, ext), Some(usage), "scancode {sc:#x} ext={ext}");
            assert_eq!(scancode_from_usage(usage), Some((sc, ext)), "usage {usage:#x}");
        }
    }

    #[test]
    fn extended_flag_disambiguates() {
        assert_eq!(usage_from_scancode(0x1D, false), Some(0xE0)); // Left Ctrl
        assert_eq!(usage_from_scancode(0x1D, true), Some(0xE4)); // Right Ctrl
        assert_eq!(usage_from_scancode(0x1C, true), Some(0x58)); // Keypad Enter
        assert_eq!(usage_from_scancode(0x7F, false), None);
    }
}
